import { readFile, mkdir, writeFile } from "node:fs/promises";
// Keep TypeScript annotations so the exact dashboard deployment file is typechecked.
const parts = [];
for (const file of ["discovery.ts", "schema.ts", "validation.ts", "index.ts"]) {
  const source = await readFile(
    new URL("../supabase/functions/agent/" + file, import.meta.url),
    "utf8",
  );
  parts.push(
    "// Source: " +
      file +
      "\n" +
      source.replace(
        /import\s*\{[^}]*\}\s*from\s*["']\.\/(?:schema|validation|discovery)\.ts["'];?\s*/g,
        "",
      ),
  );
}
await mkdir(new URL("../supabase/deploy/", import.meta.url), {
  recursive: true,
});
await writeFile(
  new URL("../supabase/deploy/agent.ts", import.meta.url),
  "// GENERATED by npm run build:edge. Edit source files under supabase/functions/agent.\n" +
    parts.join("\n"),
);
console.log(
  "Created supabase/deploy/agent.ts (single-file TypeScript deployment)",
);
